#!/usr/bin/env python3
"""Generate talos/gate4-dci-h.yaml: cross-DC test H. Two routed VNETs, one per DC, joined over the
existing IPVPN/MPLS DCI by a RouterInterconnect on each DC gateway pair (modelled on vnet-1/vnet-2).
DC1 (pod-1): red on leaf-1 (client-1), green on leaf-3 (client-3), 172.16.120.0/24.
DC2 (pod-2): blue on leaf-5 (client-5), green on leaf-7 (client-7), 172.16.121.0/24. VLAN 120 everywhere."""
import pathlib

from ms_common import NS, SVC, assoc, bd, interface, irb, md, policy, router, vlan, vnet, write

HERE = pathlib.Path(__file__).resolve().parent
WAN = "clab-srl-dcgw-wan"

# Port -> (DCI vnet label, client, all microsegmentation labels from gates 2/3 plus this gate's).
# DC1 and DC2 use different label keys so a VLAN selector in one VNET never lands on the other DC's ports.
PORTS = {
    "srl-leaf-1-ethernet-1-5": ("vnet-1", "vlan-bd-1", "client-1", {"ms-vlan": "red", "ms-dci1": "red"}),
    "srl-leaf-3-ethernet-1-5": ("vnet-3", "vlan-bd-3", "client-3", {"ms-vlan": "green", "ms-irb": "green",
                                                                    "ms-dci1": "green"}),
    "srl-leaf-5-ethernet-1-5": ("vnet-2", "vlan-bd-2", "client-5", {"ms-enf-router": "red", "ms-enf-bd": "red",
                                                                    "ms-dci2": "blue"}),
    "srl-leaf-7-ethernet-1-5": ("vnet-4", "vlan-bd-4", "client-7", {"ms-static": "green", "ms-enf-bd": "blue",
                                                                    "ms-dci2": "green"}),
}
SIDES = {  # dc: (colours, router evi, router-id, AS, bd evi, gateway, interconnect evi, domain ids, ns, dci selector)
    1: (("red", "green"), 4171, "10.41.7.1", 65471, 4172, "172.16.120.254/24", 4190, ("65000:103", "65000:203"), NS, "dc-1"),
    2: (("blue", "green"), 4181, "10.41.8.1", 65481, 4182, "172.16.121.254/24", 4191, ("65000:104", "65001:204"), WAN, "dc-2"),
}

docs = [interface(n, *v) for n, v in PORTS.items()]
vnets = []
for dc, (cols, revi, rid, asn, bevi, gw, ievi, (dom_i, dom_p), ins, sel) in SIDES.items():
    v, r, b = f"vnet-ms-dci-{dc}", f"router-ms-dci-{dc}", f"bd-ms-dci-{dc}"
    vnets.append(v)
    docs.append(vnet(v, "cross-dc", f"Test H, DC{dc} side: {', '.join(cols)} on VLAN 120, gateway {gw}. "
                     "Joined to the other DC by an IPVPN RouterInterconnect.",
                     {"routers": [router(r, revi, rid, asn)],
                      "bridgeDomains": [bd(b, bevi)],
                      "irbInterfaces": [irb(f"irb-ms-dci-{dc}", b, r, gw, host_routes=True)],
                      "vlans": [vlan(f"vlan-ms-dci{dc}-{c}", b, f"ms-dci{dc}", c, 120) for c in cols]}))
    other = SIDES[3 - dc][6]
    ric = {"apiVersion": SVC, "kind": "RouterInterconnect", "metadata": md(f"router-interconnect-ms-dci-{dc}"),
           "spec": {"routerRef": {"name": r} if ins == NS else {"name": r, "namespace": NS},
                    "nodeSelectors": [f"eda.nokia.com/dci={sel}"],
                    "primaryBGPInstance": {"domainId": dom_p},
                    "interconnectBGPInstance": {
                        "controlPlane": "IPVPN", "encapsulation": "MPLS", "domainId": dom_i, "evi": ievi,
                        "exportTarget": f"target:1:{ievi}", "importTarget": f"target:1:{other}",
                        "mpls": {"allowedTunnelTypes": ["SR-ISIS"]},
                        "routeDistinguisher": {"type": "Type 0", "assignedNumber": "2"}}}}
    ric["metadata"]["namespace"] = ins
    docs.append(ric)

docs.append(assoc("ms-assoc-dci", "cross-dc", "Test H: tags on VLANs in both DCs",
                  [("ms-red", {"vlans": ["vlan-ms-dci1-red"]}),
                   ("ms-blue", {"vlans": ["vlan-ms-dci2-blue"]}),
                   ("ms-green", {"vlans": ["vlan-ms-dci1-green", "vlan-ms-dci2-green"]})]))
# Cross-DC traffic is routed through the gateways, so whether a remote host's tag is known depends on the
# gbp-tag community surviving IPVPN re-origination. No default deny, so the result shows exactly that.
docs.append(policy("ms-policy-dci", {"virtualNetworks": vnets}, "cross-dc",
                   "Test H policy, both DC VNETs; no default deny", default_deny=False))

write(HERE / "gate4-dci-h.yaml", "# Gate 4: cross-DC test H. Generated by gen-gate4.py.", docs)
